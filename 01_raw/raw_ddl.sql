CREATE DATABASE IF NOT EXISTS SKYPOINTS_DB;
USE DATABASE SKYPOINTS_DB;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS STG;
CREATE SCHEMA IF NOT EXISTS PROD;

CREATE WAREHOUSE IF NOT EXISTS SKYPOINTS_WH
    WAREHOUSE_SIZE      = 'X-SMALL'
    AUTO_SUSPEND        = 60
    AUTO_RESUME         = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE OR REPLACE FILE FORMAT RAW.FF_PIPE_DELIMITED
    TYPE                     = 'CSV'
    FIELD_DELIMITER          = '|'
    RECORD_DELIMITER         = '\n'
    SKIP_HEADER              = 0
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    TRIM_SPACE               = TRUE
    EMPTY_FIELD_AS_NULL      = TRUE
    NULL_IF                  = ('', 'NULL', 'null');

CREATE OR REPLACE FILE FORMAT RAW.FF_JSON
    TYPE                     = 'JSON'
    STRIP_OUTER_ARRAY        = TRUE
    IGNORE_UTF8_ERRORS       = TRUE;

CREATE OR REPLACE STAGE RAW.SKYPOINTS_STAGE
    FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_PIPE_DELIMITED')
    COMMENT     = 'Internal stage for landing member flat files and partner JSON feeds';


CREATE OR REPLACE TABLE RAW.RAW_MEMBERS (
    REC_TYPE            VARCHAR(10),
    MEMBER_NAME         VARCHAR(500),
    MEMBER_ID           VARCHAR(50),
    ENROLLMENT_DATE     VARCHAR(50),
    LAST_FLIGHT_DATE    VARCHAR(50),
    TIER_CODE           VARCHAR(20),
    AGENT_NAME          VARCHAR(500),
    STATE               VARCHAR(100),
    COUNTRY             VARCHAR(100),
    DOB                 VARCHAR(50),
    IS_ACTIVE           VARCHAR(10),
    POST_CODE           VARCHAR(20),
    SOURCE_FILE         VARCHAR(500),
    LOAD_TS             TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID            VARCHAR(50)
)
CLUSTER BY (BATCH_ID)
COMMENT = 'Bronze: schema-on-read landing table for pipe-delimited member profile feeds.';

CREATE OR REPLACE TABLE RAW.RAW_REDEMPTIONS (
    JSON_PAYLOAD        VARIANT,
    SOURCE_FILE         VARCHAR(500),
    LOAD_TS             TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID            VARCHAR(50)
)
CLUSTER BY (BATCH_ID)
COMMENT = 'Bronze: native VARIANT document store preserving semi-structured partner JSON feeds.';


COPY INTO RAW.RAW_MEMBERS (
    REC_TYPE, MEMBER_NAME, MEMBER_ID, ENROLLMENT_DATE, LAST_FLIGHT_DATE,
    TIER_CODE, AGENT_NAME, STATE, COUNTRY, DOB, IS_ACTIVE, POST_CODE,
    SOURCE_FILE, BATCH_ID
)
FROM (
    SELECT
        $2, $3, $4, $5, $6, $7, $8, $9, $10,
        CASE WHEN $13 IS NOT NULL OR $12 IS NOT NULL THEN $11 ELSE $11 END,
        CASE WHEN $13 IS NOT NULL OR $12 IS NOT NULL THEN $12 ELSE $12 END,
        COALESCE($13, $10),
        METADATA$FILENAME,
        $BATCH_ID
    FROM @RAW.SKYPOINTS_STAGE
    (PATTERN => '.*members.*\.csv')
)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_PIPE_DELIMITED')
ON_ERROR    = 'CONTINUE'
FORCE       = TRUE;

COPY INTO RAW.RAW_REDEMPTIONS (JSON_PAYLOAD, SOURCE_FILE, BATCH_ID)
FROM (
    SELECT $1, METADATA$FILENAME, $BATCH_ID
    FROM @RAW.SKYPOINTS_STAGE
    (PATTERN => '.*redemptions.*\.json')
)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_JSON')
ON_ERROR    = 'CONTINUE'
FORCE       = TRUE;